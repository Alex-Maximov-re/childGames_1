export function formatNewsDate(iso: string): string {
  const [year, month, day] = iso.split('-').map(Number)
  return `${day} ${MONTHS[(month ?? 1) - 1]} ${year}`
}

export function groupNews(items: NewsNote[]): Array<{ date: string; notes: string[] }> {
  const groups: Array<{ date: string; notes: string[] }> = []
  for (const item of items) {
    const last = groups[groups.length - 1]
    if (last && last.date === item.date) last.notes.push(item.text)
    else groups.push({ date: item.date, notes: [item.text] })
  }
  return groups
}
